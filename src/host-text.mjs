/**
 * 宿主渲染层的「必须贴出」登记表（`CANVAS_CONTRACT.hostText`，0.16.1 建块）。
 *
 * 宿主（s2v、灵影、自写 harness）把 CLI 的 JSON 回包压成一段文本再给模型看；压的时候丢掉的
 * 字段，模型就当它不存在 —— `sceneDigest` 没贴出来，下一批 `baseDigest` 就只能再 read 一次；
 * `error.next[]` 没贴出来，冲突之后模型只会原样重发。所以「哪些字段必须让模型看见」是契约，
 * 不是各宿主各自的审美。
 *
 * 形状：`{ [command]: { verbatim, visible } }`。键是 CLI 子命令名，另有通配键 `"*"`：对**所有**
 * 命令的失败回包生效（含失败回包的**顶层**键，如 `hint`）。
 *  · `verbatim` —— 人话字段，逐字贴出，不改写、不截断（多行字段允许每行加统一前缀，如 `- `）；
 *    体积由页面在源头控制，宿主不再另行截断。
 *  · `visible` —— 结构化字段，值必须在文本里找得到（原值、缩写、表格一行都行）。
 * 路径是点语法，`[]` = 数组的每一项，以 `[]` 开头 = 回包本身是数组（`list-canvases`）。
 * 单份回包里没有的字段不查；但每条登记路径在该命令至少一份夹具里要解析得到（无死路径，
 * 夹具与闸在 `test/`）。
 *
 * 「读者忽略不认识的字段」这条规则**不适用于**这里登记过的字段：宿主渲染层必须贴出它们。
 *
 * 独立成模块、只由 `contract.mjs` 的 `CANVAS_CONTRACT` 引用：契约在画布首包里，这份纯数据
 * 别处不要 import。守护进程闭包（daemon / policy / session / common / connection-code）不读它。
 */
